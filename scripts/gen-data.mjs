// Generates src/generated/{colours,shapes}.ts from data/cards.json (exported by the design repo:
// pokerzon-docs design/pokerzon/cards/source/build_cards.py → cards/lib/cards.json).
// Two modules so the core (colours) stays small and the shapes load only with the renderers.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const root = new URL("..", import.meta.url);
const data = JSON.parse(readFileSync(new URL("data/cards.json", root), "utf8"));
mkdirSync(new URL("src/generated/", root), { recursive: true });
const head = `// GENERATED by scripts/gen-data.mjs from data/cards.json — do not edit.
// Design source: ${data.source} (v${data.version}, ${data.date}).
`;
writeFileSync(new URL("src/generated/colours.ts", root), `${head}import type { CardsData } from "../core/data-types.ts";
export const COLOUR_DATA: CardsData["colours"] = ${JSON.stringify(data.colours)};
`);
writeFileSync(new URL("src/generated/shapes.ts", root), `${head}import type { CardsData } from "../core/data-types.ts";
export const VIEWBOX: CardsData["viewBox"] = ${JSON.stringify(data.viewBox)};
export const SUIT_PATHS: CardsData["suits"] = ${JSON.stringify(data.suits)};
export const RANK_GLYPHS: CardsData["ranks"] = ${JSON.stringify(data.ranks)};
`);
console.log("src/generated/colours.ts, shapes.ts");

// styles/themes/pokerzon.css — the colour tokens (cards.css imports it)
const C = data.colours;
const names = { spade: "spade", heart: "heart", diamond: "diamond", club: "club" };
const tok = (deck) => Object.keys(names).map((s) => {
  const k = C.decks[deck][s];
  const [u, l, one] = C.onLight[k], [tu, tl] = C.tint[k], [du, dl, d1] = C.onDark[k];
  return `--pz-${s}-u:${u};--pz-${s}-l:${l};--pz-${s}-1:${one};--pz-${s}-tu:${tu};--pz-${s}-tl:${tl};--pz-${s}-du:${du};--pz-${s}-dl:${dl};--pz-${s}-d1:${d1};`;
});
const [xu, xl, x1] = C.unknown.light, [xdu, xdl, xd1] = C.unknown.dark;
const two = tok("two").filter((t) => t.startsWith("--pz-diamond") || t.startsWith("--pz-club"));
writeFileSync(new URL("styles/themes/pokerzon.css", root), `/* @pokerzon/cards — PokerZON theme: colour tokens (GENERATED by scripts/gen-data.mjs from data/cards.json).
   Four-colour deck by default; [data-deck="two"] on the card or any ancestor switches to the two-colour deck. */
:root{
 ${tok("four").join("\n ")}
 --pz-x-u:${xu};--pz-x-l:${xl};--pz-x-1:${x1};--pz-x-tu:${xu};--pz-x-tl:${xl};--pz-x-du:${xdu};--pz-x-dl:${xdl};--pz-x-d1:${xd1};
 --pz-split-neutral-dark-u:${C.splitNeutralDark[0]};--pz-split-neutral-dark-l:${C.splitNeutralDark[1]};--pz-muck:${C.muck};
 --pz-card-face:#FFFFFF;--pz-card-edge:#E3E7E8;--pz-card-edge-dark:#3A4245;--pz-slot:#C9D1D3;--pz-slot-dark:#3A4245;
 --pz-rank-font:"PZ Cards Rank",Outfit,system-ui,sans-serif;
}
[data-deck="two"]{
 ${two.join("\n ")}
}
`);
console.log("styles/themes/pokerzon.css");
